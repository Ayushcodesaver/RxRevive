"""Gemini assist tests: prompt construction, JSON parsing, honest failures.

The network call is mocked — tests never hit the Gemini API. A live-call test
activates automatically when GEMINI_API_KEY is present in the environment.
"""

import os

import pytest

from app.services import assist_service
from app.services.assist_service import (
    AssistUnavailableError,
    build_prompt,
    draft_suggestions,
)

CONTEXT = {
    "resume_text": "Priya Sharma. Data scientist, 3 years of experience, python, scikit-learn, docker, healthcare analytics. B.Tech in Computer Science.",
    "job_description": "Data scientist role: python, machine learning, nlp, tensorflow, kubernetes, communication. 2+ years experience.",
    "matched": ["python", "docker", "machine learning"],
    "missing": ["tensorflow", "kubernetes", "nlp"],
    "match_score": 47,
    "similarity_pct": 24.2,
    "skill_pct": 57.1,
}

GEMINI_JSON = """{
  "summary": "Data scientist with three years of experience building machine learning models for healthcare analytics, targeting NLP-heavy product work.",
  "bullets": [
    {"missing_skill": "nlp", "suggestion": "Built NLP models to classify clinical notes, improving triage speed by 30%", "grounding": "Experience - MedAnalytics"},
    {"missing_skill": "tensorflow", "suggestion": "Extended the scikit-learn pipelines with [ADD: which framework you actually used] models", "grounding": "Skills section"}
  ],
  "keywords": ["natural language processing", "tensorflow", "kubernetes"],
  "cautions": "Confirm the 30% figure and add the framework name where marked."
}"""


def test_prompt_contains_context_and_rules():
    prompt = build_prompt(**CONTEXT)
    assert "Priya Sharma" in prompt
    assert "tensorflow" in prompt
    assert "Never invent employers" in prompt
    assert "47%" in prompt
    assert "[ADD:" in prompt  # the model is taught the placeholder convention


def test_prompt_clips_long_inputs():
    long_resume = "word " * 20_000
    prompt = build_prompt(long_resume, long_resume, [], [], 50, 50, 50)
    assert len(prompt) < 4 * assist_service.MAX_CONTEXT_CHARS + 2000


def test_draft_suggestions_parses_gemini_json(monkeypatch):
    monkeypatch.setattr(assist_service, "call_gemini", lambda prompt: __import__("json").loads(GEMINI_JSON))
    result = draft_suggestions(**CONTEXT)
    assert result["summary"].startswith("Data scientist")
    assert len(result["bullets"]) == 2
    assert result["bullets"][0]["missing_skill"] == "nlp"
    assert result["keywords"][0] == "natural language processing"
    assert result["disclaimer"].startswith("These drafts were generated by Gemini")
    assert result["model"] == assist_service.get_settings().gemini_model


def test_draft_suggestions_rejects_empty_output(monkeypatch):
    monkeypatch.setattr(assist_service, "call_gemini", lambda prompt: {"summary": "", "bullets": []})
    with pytest.raises(AssistUnavailableError):
        draft_suggestions(**CONTEXT)


def test_draft_suggestions_drops_malformed_bullets(monkeypatch):
    raw = {"summary": "ok", "bullets": ["not a dict", {"missing_skill": "x", "suggestion": "real bullet", "grounding": "y"}], "keywords": []}
    monkeypatch.setattr(assist_service, "call_gemini", lambda prompt: raw)
    result = draft_suggestions(**CONTEXT)
    assert len(result["bullets"]) == 1


def test_missing_key_is_honest(monkeypatch):
    settings = assist_service.get_settings()
    monkeypatch.setattr(settings, "gemini_api_key", "")  # same cached instance the service uses
    with pytest.raises(AssistUnavailableError, match="GEMINI_API_KEY is not configured"):
        assist_service.call_gemini("prompt")


@pytest.mark.skipif(not os.environ.get("GEMINI_API_KEY"), reason="no GEMINI_API_KEY in environment")
def test_live_gemini_call():
    result = assist_service.call_gemini(build_prompt(**CONTEXT))
    assert "summary" in result
